function initialLocale(): AppLocale {
  const saved = localStorage.getItem('tt-locale')
  return saved === 'fr' || saved === 'en' ? saved : 'fr'
}

const i18n = createI18n({
  legacy: false,
  globalInjection: true,
  locale: initialLocale(),
  fallbackLocale: 'fr',
  messages: { fr, en },
})

export function setLocale(l: AppLocale) {
  i18n.global.locale.value = l
  localStorage.setItem('tt-locale', l)
  document.documentElement.lang = l
  setCategoryLocale(l)
}

// Sync category labels (and <html lang>) with the initial locale at startup
setCategoryLocale(i18n.global.locale.value)
document.documentElement.lang = i18n.global.locale.value

export default i18n
